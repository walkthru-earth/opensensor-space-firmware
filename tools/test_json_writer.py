"""Host checks for the shared bounded JSON writer, firmware/common/src/json_writer.h.

format_real() must print every double the way JavaScript String() does.
tools/fixtures/json/js_numbers.txt holds that golden output, generated by
Node from the vendored STAC fixtures, edge cases and seeded random doubles
(tools/fixtures/json/generate_js_numbers.mjs). Synthetic tests prove no board
behavior.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import subprocess
import tempfile

from host_cxx import CXX_STD


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sanitize", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    with tempfile.TemporaryDirectory(prefix="os-json-test-") as directory:
        executable = Path(directory) / "json-test"
        command = [
            "clang++", CXX_STD, "-Wall", "-Wextra", "-Werror",
            "-I", str(root / "firmware/common/src"),
            str(root / "tools/test_json_writer.cpp"), "-o", str(executable),
        ]
        if args.sanitize:
            command += ["-fsanitize=address,undefined", "-fno-omit-frame-pointer"]
        subprocess.run(command, check=True)
        subprocess.run([str(executable), str(root / "tools/fixtures/json/js_numbers.txt")], check=True)


if __name__ == "__main__":
    main()
